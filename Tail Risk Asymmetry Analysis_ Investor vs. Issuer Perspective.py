def investor_payoff_from_S(S_input):
    """
    Calculates the investor's payoff based on the simulated asset prices.

    Args:
        S_input (np.ndarray): Simulated asset prices over time for n simulations.

    Returns:
        tuple: A tuple containing:
            - payoff (np.ndarray): Array of final payoffs for each simulation.
            - case (np.ndarray): Array indicating the payoff case for each simulation.
            - KI_local (np.ndarray): Array indicating if a Knock-In event occurred for each simulation.
    """
    # Recalculate R_check, WP_check, R_all, and KI based on the S_input
    R_check = S_input[check_day,:,:] / S0
    WP_check = np.minimum(np.minimum(R_check[:,:,0], R_check[:,:,1]), R_check[:,:,2])

    R_all_local = S_input / S0
    KI_local = (R_all_local < kib).any(axis=0).any(axis=1)

    payoff_local = np.zeros(n)
    case_local = np.array(['']*n, dtype=object)

    for j in range(n):
        done = False
        for i in range(len(check_day)):
            if WP_check[i, j] >= strike_price[i]:
                payoff_local[j] = 1.0 + coupon[i]
                case_local[j] = f"autocall_{i+1}"
                done = True
                break

        if not done:
            WP_T = min(R_all_local[-1, j, 0], R_all_local[-1, j, 1], R_all_local[-1, j, 2])
            if WP_T >= maturity_strike:
                payoff_local[j] = 1.0 + maturity_coupon
                case_local[j] = "maturity_good"
            else:
                if (KI_local[j] == False):
                    payoff_local[j] = 1.0 + maturity_coupon
                    case_local[j] = "maturity_noKI"
                else:
                    payoff_local[j] = WP_T
                    case_local[j] = "maturity_KI_worst"
    return payoff_local, case_local, KI_local

