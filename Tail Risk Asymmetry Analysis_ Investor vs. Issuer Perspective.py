def issuer_proxy(W, hedge_step=5, tc=0.0005):
    idx = np.arange(0, W.shape[0], hedge_step)
    if idx[-1] != W.shape[0]-1:
        idx = np.append(idx, W.shape[0]-1)

    W_h = W[idx, :]
    dW = np.diff(W_h, axis=0)
    turnover = np.sum(np.abs(dW), axis=0)
    cost = tc * turnover
    qv = np.sum(dW**2, axis=0)
    hedge_error = qv * hedge_step
    risk_index = (cost + hedge_error) * KI_weight

    return risk_index

