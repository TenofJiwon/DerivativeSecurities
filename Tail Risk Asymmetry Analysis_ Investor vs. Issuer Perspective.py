def simulate_S_with_corr(corr_level):
    corr_mat_s = np.ones((3,3)) * corr_level
    np.fill_diagonal(corr_mat_s, 1.0)
    L_s = np.linalg.cholesky(corr_mat_s)

    S_s = np.zeros((total_day+1, n, 3))
